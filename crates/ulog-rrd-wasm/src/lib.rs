//! ulog-rrd for the browser: ULog bytes in, `.rrd` bytes out, for the Rerun web viewer's
//! `open_channel().send_rrd()`.

use wasm_bindgen::prelude::*;

/// The ulog-rrd version.
#[wasm_bindgen]
pub fn version() -> String {
    ulog_rrd::VERSION.to_owned()
}

/// The Rerun version the recordings are encoded for: the `@rerun-io/web-viewer` to use.
#[wasm_bindgen(js_name = rerunVersion)]
pub fn rerun_version() -> String {
    ulog_rrd::RERUN_VERSION.to_owned()
}

/// What the caller decides. Every field has the library's default; set the ones to change.
#[wasm_bindgen(getter_with_clone)]
#[derive(Default)]
pub struct Options {
    /// The application the recording belongs to. Rerun applies a blueprint by this id.
    #[wasm_bindgen(js_name = applicationId)]
    pub application_id: Option<String>,
    /// The recording the rows join; unset makes one up.
    #[wasm_bindgen(js_name = recordingId)]
    pub recording_id: Option<String>,
    /// Put before every entity path; unset puts the rows at the root.
    #[wasm_bindgen(js_name = entityPathPrefix)]
    pub entity_path_prefix: Option<String>,
    /// The duration timeline the rows sit on.
    pub timeline: Option<String>,
    /// Subtracted from every ULog timestamp, in microseconds.
    #[wasm_bindgen(js_name = timeOffsetUs)]
    pub time_offset_us: Option<f64>,
    /// Log every numeric field of every topic as a series under `timeseries/`.
    pub scalars: Option<bool>,
    /// Where PX4's local frame, north-east-down, sits in the caller's world, logged as the transform of
    /// the prefix root: a translation `[x, y, z]` in metres and a rotation quaternion `[x, y, z, w]`.
    pub translation: Option<Vec<f32>>,
    pub rotation: Option<Vec<f32>>,
    /// Append the blueprint, so the viewer opens with the vehicle beside the whole flight and the
    /// log below. Only for the default application id, which the blueprint names.
    pub blueprint: Option<bool>,
}

#[wasm_bindgen]
impl Options {
    #[wasm_bindgen(constructor)]
    pub fn new() -> Self {
        Self::default()
    }
}

fn array<const N: usize>(v: &Option<Vec<f32>>, what: &str) -> Result<Option<[f32; N]>, JsError> {
    v.as_ref()
        .map(|v| <[f32; N]>::try_from(v.as_slice()).map_err(|_| JsError::new(&format!("{what} takes {N} numbers"))))
        .transpose()
}

impl TryFrom<&Options> for ulog_rrd::Options {
    type Error = JsError;

    fn try_from(o: &Options) -> Result<Self, JsError> {
        let d = ulog_rrd::Options::default();
        Ok(ulog_rrd::Options {
            application_id: o.application_id.clone().unwrap_or(d.application_id),
            recording_id: o.recording_id.clone(),
            entity_path_prefix: o.entity_path_prefix.clone(),
            timeline: o.timeline.clone().unwrap_or(d.timeline),
            time_offset_us: o.time_offset_us.map_or(d.time_offset_us, |t| t as i64),
            scalars: o.scalars.unwrap_or(d.scalars),
            translation: array(&o.translation, "translation")?,
            rotation: array(&o.rotation, "rotation")?,
        })
    }
}

/// The blueprint for a recording with the default application id, as `.rbl` bytes: the vehicle up
/// close beside the whole flight, the log below. Generated by `scripts/blueprint.py` at build time.
const BLUEPRINT: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/blueprint.rbl"));

/// The blueprint as `.rbl` bytes, to send to the viewer before or after the recording.
#[wasm_bindgen]
pub fn blueprint() -> Result<Vec<u8>, JsError> {
    if BLUEPRINT.is_empty() {
        return Err(JsError::new("this build has no blueprint: run scripts/blueprint.py before building"));
    }
    Ok(BLUEPRINT.to_vec())
}

/// The recording of a ULog as `.rrd` bytes.
#[wasm_bindgen]
pub fn convert(ulog: &[u8], options: Option<Options>) -> Result<Vec<u8>, JsError> {
    let opts = options.as_ref().map(ulog_rrd::Options::try_from).transpose()?.unwrap_or_default();
    let mut rrd = ulog_rrd::convert(ulog, &opts).map_err(|e| JsError::new(&e.0))?;
    if options.as_ref().is_some_and(|o| o.blueprint == Some(true)) {
        if opts.application_id != ulog_rrd::Options::default().application_id {
            return Err(JsError::new("the blueprint applies to the default application id only"));
        }
        // An .rrd is a sequence of streams: the viewer reads the blueprint after the recording.
        rrd.extend_from_slice(&blueprint()?);
    }
    Ok(rrd)
}
